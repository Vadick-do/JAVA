CREATE TABLE slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    resource_id BIGINT NOT NULL REFERENCES resources (id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT slots_hour_boundary CHECK (isfinite(starts_at) AND starts_at = date_trunc('hour', starts_at, 'UTC')),
    CONSTRAINT slots_hour_duration CHECK (ends_at = starts_at + INTERVAL '1 hour'),
    CONSTRAINT slots_resource_start_unique UNIQUE (resource_id, starts_at)
);
